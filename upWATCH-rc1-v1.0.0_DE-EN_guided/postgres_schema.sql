
CREATE TABLE IF NOT EXISTS users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL, salt TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'viewer' CHECK (role IN ('admin','manager','viewer')));
CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, username TEXT NOT NULL, csrf TEXT NOT NULL, expires DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS user_mfa (username TEXT PRIMARY KEY REFERENCES users(username) ON DELETE CASCADE, secret_enc TEXT NOT NULL, last_step BIGINT NOT NULL DEFAULT -1);
CREATE TABLE IF NOT EXISTS mfa_pending (username TEXT PRIMARY KEY REFERENCES users(username) ON DELETE CASCADE, secret_enc TEXT NOT NULL, expires DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS mfa_recovery (username TEXT NOT NULL REFERENCES users(username) ON DELETE CASCADE,code_hash TEXT NOT NULL,PRIMARY KEY(username,code_hash));
CREATE TABLE IF NOT EXISTS auth_challenges (token_hash TEXT PRIMARY KEY,username TEXT NOT NULL,expires DOUBLE PRECISION NOT NULL,client_ip TEXT NOT NULL,attempts BIGINT NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS monitors (
 id TEXT PRIMARY KEY, alias TEXT NOT NULL, kind TEXT NOT NULL, target TEXT NOT NULL,
 config TEXT NOT NULL DEFAULT '{}', interval BIGINT NOT NULL DEFAULT 60,
 timeout BIGINT NOT NULL DEFAULT 5, failure_threshold BIGINT NOT NULL DEFAULT 3,
 recovery_threshold BIGINT NOT NULL DEFAULT 2, warning_latency_ms DOUBLE PRECISION,
 critical_latency_ms DOUBLE PRECISION, notify_down BIGINT NOT NULL DEFAULT 0,
 notify_up BIGINT NOT NULL DEFAULT 0, maintenance BIGINT NOT NULL DEFAULT 0,
 position BIGINT NOT NULL DEFAULT 0, revision BIGINT NOT NULL DEFAULT 1,
 status TEXT, checked DOUBLE PRECISION, latency DOUBLE PRECISION, code BIGINT, detail TEXT,
 failure_count BIGINT NOT NULL DEFAULT 0, recovery_count BIGINT NOT NULL DEFAULT 0,
 next_check DOUBLE PRECISION NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS checks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, monitor_id TEXT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
 checked DOUBLE PRECISION NOT NULL, status TEXT NOT NULL, latency DOUBLE PRECISION, code BIGINT, error_code TEXT, detail TEXT,
 metrics TEXT NOT NULL DEFAULT '{}');
CREATE INDEX IF NOT EXISTS ix_checks_monitor_time ON checks(monitor_id,checked DESC);
CREATE TABLE IF NOT EXISTS events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, monitor_id TEXT REFERENCES monitors(id) ON DELETE SET NULL,
 created DOUBLE PRECISION NOT NULL, event_type TEXT NOT NULL, severity TEXT NOT NULL, detail TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS ix_events_created ON events(created DESC);
CREATE TABLE IF NOT EXISTS incidents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,monitor_id TEXT REFERENCES monitors(id) ON DELETE SET NULL,
 started DOUBLE PRECISION NOT NULL, ended DOUBLE PRECISION, reason TEXT, alert_queued BIGINT NOT NULL DEFAULT 0, alert_deferred BIGINT NOT NULL DEFAULT 0);
CREATE UNIQUE INDEX IF NOT EXISTS ix_incident_open ON incidents(monitor_id) WHERE ended IS NULL;
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,created DOUBLE PRECISION NOT NULL,actor TEXT NOT NULL,action TEXT NOT NULL,
 object_id TEXT, client_ip TEXT, success BIGINT NOT NULL, detail TEXT);
CREATE TABLE IF NOT EXISTS dependencies (
 parent_id TEXT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
 child_id TEXT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
 PRIMARY KEY(parent_id,child_id),CHECK(parent_id<>child_id));
CREATE TABLE IF NOT EXISTS maintenance_windows (
 id TEXT PRIMARY KEY, monitor_id TEXT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
 starts DOUBLE PRECISION NOT NULL, ends DOUBLE PRECISION NOT NULL,
 recurrence TEXT NOT NULL DEFAULT 'once' CHECK(recurrence IN ('once','daily','weekly')),
 timezone TEXT NOT NULL DEFAULT 'UTC',
 weekdays TEXT NOT NULL DEFAULT '[]',
 start_local TEXT NOT NULL DEFAULT '00:00',end_local TEXT NOT NULL DEFAULT '00:00',
 CHECK(ends>starts));
CREATE TABLE IF NOT EXISTS snmp_counters (
 monitor_id TEXT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
 oid TEXT NOT NULL, value NUMERIC(20,0) NOT NULL, observed DOUBLE PRECISION NOT NULL, uptime BIGINT,
 PRIMARY KEY(monitor_id,oid));
CREATE TABLE IF NOT EXISTS rollups (
 monitor_id TEXT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
 period TEXT NOT NULL, bucket BIGINT NOT NULL, total BIGINT NOT NULL, success BIGINT NOT NULL,
 latency_sum DOUBLE PRECISION NOT NULL,latency_count BIGINT NOT NULL,latency_min DOUBLE PRECISION,latency_max DOUBLE PRECISION,
 PRIMARY KEY(monitor_id,period,bucket));
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS snmp_profiles (
 id TEXT PRIMARY KEY, label TEXT NOT NULL UNIQUE, username TEXT NOT NULL,
 auth_protocol TEXT NOT NULL CHECK(auth_protocol IN ('sha1','sha256')),
 auth_enc TEXT NOT NULL, priv_enc TEXT NOT NULL, created DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS mail_outbox (
 id TEXT PRIMARY KEY, created DOUBLE PRECISION NOT NULL, next_attempt DOUBLE PRECISION NOT NULL,
 recipient TEXT NOT NULL, subject TEXT NOT NULL, body TEXT NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('pending','sending','sent','failed')),
 attempts BIGINT NOT NULL DEFAULT 0, locked_until DOUBLE PRECISION, sent_at DOUBLE PRECISION, last_error TEXT);
CREATE INDEX IF NOT EXISTS ix_mail_pending ON mail_outbox(status,next_attempt);
CREATE TABLE IF NOT EXISTS widget_groups (
 id TEXT PRIMARY KEY, name TEXT NOT NULL UNIQUE,
 description TEXT NOT NULL DEFAULT '', position BIGINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS widget_tags (
 id TEXT PRIMARY KEY, name TEXT NOT NULL UNIQUE,
 color TEXT NOT NULL CHECK(length(color)=7 AND substr(color,1,1)='#'));
CREATE TABLE IF NOT EXISTS widget_tag_links (
 monitor_id TEXT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
 tag_id TEXT NOT NULL REFERENCES widget_tags(id) ON DELETE CASCADE,
 PRIMARY KEY(monitor_id,tag_id));
CREATE TABLE IF NOT EXISTS widget_placement (
 monitor_id TEXT PRIMARY KEY REFERENCES monitors(id) ON DELETE CASCADE,
 group_id TEXT REFERENCES widget_groups(id) ON DELETE SET NULL,
 position BIGINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS widget_group_preferences (
 username TEXT NOT NULL REFERENCES users(username) ON DELETE CASCADE,
 group_id TEXT NOT NULL REFERENCES widget_groups(id) ON DELETE CASCADE,
 collapsed BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(username,group_id));
CREATE TABLE IF NOT EXISTS worker_heartbeat (name TEXT PRIMARY KEY, updated DOUBLE PRECISION NOT NULL);
CREATE INDEX IF NOT EXISTS ix_incidents_monitor ON incidents(monitor_id, started DESC);

CREATE UNIQUE INDEX IF NOT EXISTS ix_widget_groups_ci ON widget_groups (lower(name));
CREATE UNIQUE INDEX IF NOT EXISTS ix_widget_tags_ci ON widget_tags (lower(name));

-- RC3 user grants: group/tag visibility is an OR-combination.
CREATE TABLE IF NOT EXISTS user_group_grants (username TEXT NOT NULL REFERENCES users(username) ON DELETE CASCADE ON UPDATE CASCADE, group_id TEXT NOT NULL REFERENCES widget_groups(id) ON DELETE CASCADE, PRIMARY KEY(username,group_id));
CREATE TABLE IF NOT EXISTS user_tag_grants (username TEXT NOT NULL REFERENCES users(username) ON DELETE CASCADE ON UPDATE CASCADE, tag_id TEXT NOT NULL REFERENCES widget_tags(id) ON DELETE CASCADE, PRIMARY KEY(username,tag_id));

-- Administrator-controlled per-user notification subscriptions. No secrets stored.
CREATE TABLE IF NOT EXISTS alert_subscriptions (
 username TEXT PRIMARY KEY REFERENCES users(username) ON DELETE CASCADE ON UPDATE CASCADE,
 email TEXT NOT NULL, notify_down BIGINT NOT NULL DEFAULT 0, notify_up BIGINT NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS ix_audit_created ON audit(created DESC);
CREATE INDEX IF NOT EXISTS ix_events_monitor_created ON events(monitor_id,created DESC);
CREATE INDEX IF NOT EXISTS ix_rollups_period_bucket ON rollups(period,bucket);
